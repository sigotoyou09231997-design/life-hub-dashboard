/** 大会名(「2026-27 English Premier League」のような、年を除いた形)を日本語に。載っていなければ、そのまま。 */
export function competitionNameJa(name: string): string {
  const rules: [RegExp, string][] = [
    [/^English Premier League$/i, "プレミアリーグ"],
    [/^(Spanish )?LA ?LIGA$/i, "ラ・リーガ"],
    [/^German Bundesliga$/i, "ブンデスリーガ"],
    [/^Italian Serie A$/i, "セリエA"],
    [/^French Ligue 1$/i, "リーグ・アン"],
    [/^Dutch Eredivisie$/i, "エールディヴィジ"],
    [/^Portuguese Primeira Liga$/i, "プリメイラ・リーガ"],
    [/^Scottish Premiership$/i, "スコットランド・プレミアシップ"],
    [/^Belgian Pro League$/i, "ベルギー・プロリーグ"],
    [/^English League Championship$/i, "チャンピオンシップ"],
    [/^UEFA Champions League$/i, "UEFAチャンピオンズリーグ"],
    [/^UEFA Europa League$/i, "UEFAヨーロッパリーグ"],
    [/^UEFA Conference League$/i, "UEFAカンファレンスリーグ"],
    [/^League Phase$/i, "リーグフェーズ"],
    [/^Knockout Round Playoffs?$/i, "プレーオフ"],
    [/^Round of 16$/i, "ラウンド16"],
    [/^Quarterfinals?$/i, "準々決勝"],
    [/^Semifinals?$/i, "準決勝"],
    [/^Final$/i, "決勝"],
  ];
  const hit = rules.find(([re]) => re.test(name));
  return hit ? hit[1] : name;
}
